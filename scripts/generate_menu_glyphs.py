"""Keep the HUD font atlas aware of every non-ASCII character in plugin source."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/menu_glyphs.hpp'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    chars = set()
    for path in (ROOT / 'src').rglob('*'):
        if path != OUTPUT and path.suffix in ('.hpp', '.cpp'):
            chars.update(c for c in path.read_text(encoding='utf-8') if ord(c) > 127)
    text = ''.join(sorted(chars))
    result = ('// Generated by scripts/generate_menu_glyphs.py; do not edit.\n'
              '#pragma once\nnamespace dango::hud {\n'
              'inline constexpr char MenuGlyphs[] = u8"' + text + '";\n}\n')
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != result:
            raise SystemExit('Menu glyph coverage is stale; run scripts/generate_menu_glyphs.py')
    else:
        OUTPUT.write_text(result, encoding='utf-8')
    print(f'Verified complete source text coverage: {len(chars)} non-ASCII characters')


if __name__ == '__main__':
    main()
